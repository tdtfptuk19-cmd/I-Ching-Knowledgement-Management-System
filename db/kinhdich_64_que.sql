/* ===== KIEM TRA SAU KHI NAP (chay tung cau) ===== */
-- 1) Dem: 8 / 64 / 386
SELECT (SELECT COUNT(*) FROM trigrams) AS trigrams, (SELECT COUNT(*) FROM hexagrams) AS hexagrams, (SELECT COUNT(*) FROM hexagram_lines) AS lines_total;
-- 2) 64 ma bit khac nhau va 64 to hop Thuong/Ha khac nhau (ky vong 64, 64)
SELECT COUNT(DISTINCT binary_code) AS n_code, COUNT(DISTINCT upper_code + lower_code) AS n_combo FROM hexagrams;
-- 3) Que nao khong ghep duoc voi que don (ky vong 0 dong)
SELECT h.hexagram_id, h.name_vn FROM hexagrams h LEFT JOIN v_hexagram_trigrams v ON v.hexagram_id = h.hexagram_id WHERE v.hexagram_id IS NULL;
-- 4) Quy tac cap Van Vuong: que le/chan lien ke la dao thu tu cac hao, que doi xung thi lat am duong (ky vong 0 dong)
SELECT a.hexagram_id AS que_le, a.binary_code, b.binary_code AS que_chan
FROM hexagrams a JOIN hexagrams b ON b.hexagram_id = a.hexagram_id + 1
WHERE a.hexagram_id % 2 = 1
  AND b.binary_code <> CASE WHEN REVERSE(a.binary_code) = a.binary_code
                            THEN TRANSLATE(a.binary_code, '01', '10') ELSE REVERSE(a.binary_code) END;
-- 5) yin_yang cua hao khop ma bit (ky vong 0 dong)
SELECT l.hexagram_id, l.position FROM hexagram_lines l JOIN hexagrams h ON h.hexagram_id = l.hexagram_id
WHERE l.position <= 6 AND l.yin_yang <> CAST(SUBSTRING(h.binary_code, 7 - l.position, 1) AS INT);
-- 6) Cac que moc
SELECT hexagram_id, binary_code, name_vn FROM hexagrams WHERE hexagram_id IN (1, 2, 11, 12, 17, 60, 63, 64) ORDER BY hexagram_id;
